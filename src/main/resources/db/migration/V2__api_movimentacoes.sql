CREATE TABLE equipe (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setor VARCHAR(80) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX ux_equipe_setor_nome_lower ON equipe (setor, LOWER(nome));

CREATE TABLE recebedor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setor VARCHAR(80) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    matricula VARCHAR(40) NOT NULL,
    pin_hash VARCHAR(255) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    falhas_pin INTEGER NOT NULL DEFAULT 0,
    inicio_janela_falhas TIMESTAMP WITH TIME ZONE,
    bloqueado_ate TIMESTAMP WITH TIME ZONE
);

CREATE UNIQUE INDEX ux_recebedor_setor_matricula_lower ON recebedor (setor, LOWER(matricula));

CREATE TABLE empenho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setor VARCHAR(80) NOT NULL,
    operador_id BIGINT NOT NULL REFERENCES usuario(id),
    recebedor_id BIGINT NOT NULL REFERENCES recebedor(id),
    equipe_id BIGINT NOT NULL REFERENCES equipe(id),
    status VARCHAR(40) NOT NULL CHECK (status IN (
        'PENDENTE', 'CANCELADO', 'ABERTO', 'DEVOLVIDO_PARCIALMENTE', 'ENCERRADO', 'EXTRAVIADO'
    )),
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    observacao VARCHAR(500) NOT NULL DEFAULT '',
    confirmado_em TIMESTAMP WITH TIME ZONE,
    confirmado_por BIGINT REFERENCES usuario(id),
    cancelado_por BIGINT REFERENCES usuario(id),
    confirmado_por_pin BOOLEAN NOT NULL DEFAULT FALSE,
    justificativa_pin VARCHAR(500),
    versao BIGINT NOT NULL DEFAULT 0
);

CREATE INDEX ix_empenho_setor_status_data ON empenho (setor, status, data_hora DESC);
CREATE INDEX ix_empenho_recebedor_data ON empenho (recebedor_id, data_hora DESC);
CREATE INDEX ix_empenho_equipe_data ON empenho (equipe_id, data_hora DESC);

ALTER TABLE item_material
    ADD COLUMN empenho_pendente_id BIGINT REFERENCES empenho(id),
    ADD COLUMN versao BIGINT NOT NULL DEFAULT 0;

CREATE INDEX ix_item_material_empenho_pendente ON item_material (empenho_pendente_id);

CREATE TABLE item_empenho (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empenho_id BIGINT NOT NULL REFERENCES empenho(id),
    item_material_id BIGINT NOT NULL REFERENCES item_material(id),
    situacao VARCHAR(30) CHECK (situacao IS NULL OR situacao IN ('EMPENHADO', 'DEVOLVIDO', 'EXTRAVIADO')),
    extraviado_em TIMESTAMP WITH TIME ZONE,
    extravio_registrado_por BIGINT REFERENCES usuario(id),
    CONSTRAINT ux_item_empenho_item UNIQUE (empenho_id, item_material_id)
);

CREATE INDEX ix_item_empenho_empenho ON item_empenho (empenho_id);
CREATE INDEX ix_item_empenho_material ON item_empenho (item_material_id);

CREATE TABLE devolucao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    empenho_id BIGINT NOT NULL REFERENCES empenho(id),
    registrado_por BIGINT NOT NULL REFERENCES usuario(id),
    devolvido_por BIGINT NOT NULL REFERENCES recebedor(id),
    data_hora TIMESTAMP WITH TIME ZONE NOT NULL,
    observacao VARCHAR(500) NOT NULL DEFAULT ''
);

CREATE INDEX ix_devolucao_empenho_data ON devolucao (empenho_id, data_hora);

CREATE TABLE item_devolucao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    devolucao_id BIGINT NOT NULL REFERENCES devolucao(id),
    item_empenho_id BIGINT NOT NULL UNIQUE REFERENCES item_empenho(id),
    condicao VARCHAR(20) NOT NULL CHECK (condicao IN ('BOM', 'AVARIADO')),
    observacao VARCHAR(500) NOT NULL DEFAULT ''
);

CREATE INDEX ix_item_devolucao_devolucao ON item_devolucao (devolucao_id);
