CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    matricula VARCHAR(40) NOT NULL,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(40) NOT NULL CHECK (perfil IN ('ADMINISTRADOR_SISTEMA', 'ADMINISTRADOR_ESTOQUE', 'OPERADOR_ESTOQUE')),
    setor VARCHAR(80) NOT NULL,
    turno VARCHAR(40),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    falhas_login INTEGER NOT NULL DEFAULT 0,
    inicio_janela_falhas TIMESTAMP,
    bloqueado_ate TIMESTAMP
);

CREATE UNIQUE INDEX ux_usuario_matricula_lower ON usuario (LOWER(matricula));
CREATE UNIQUE INDEX ux_usuario_administrador_sistema_unico ON usuario (perfil)
    WHERE perfil = 'ADMINISTRADOR_SISTEMA';

CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setor VARCHAR(80) NOT NULL,
    codigo VARCHAR(40) NOT NULL,
    nome VARCHAR(120) NOT NULL,
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE UNIQUE INDEX ux_material_setor_codigo_lower ON material (setor, LOWER(codigo));
CREATE INDEX ix_material_setor ON material (setor);

CREATE TABLE item_material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES material(id),
    setor VARCHAR(80) NOT NULL,
    numero_patrimonio VARCHAR(80) NOT NULL,
    status VARCHAR(30) NOT NULL CHECK (status IN ('DISPONIVEL', 'EMPENHADO', 'AVARIADO', 'EXTRAVIADO', 'INATIVO'))
);

CREATE UNIQUE INDEX ux_item_setor_numero_patrimonio_lower ON item_material (setor, LOWER(numero_patrimonio));
CREATE INDEX ix_item_material_material_id ON item_material (material_id);